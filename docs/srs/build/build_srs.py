    "1D axial profile. The virtual OES uses a collisional-radiative (CR) model of the argon 1s and 2p levels "
    f"{R('zhupu_cr')} and NIST line data {R('nist')} to synthesise a spectrum, which is then analysed with a Boltzmann "
    "plot, line-ratio methods and rotational or Doppler gas-temperature methods. The virtual Langmuir probe computes an "
    f"RF-distorted I-V curve and analyses it with OML theory and the Druyvesteyn method {R('chen', 'druyvesteyn')}. For Stage 2, "
    "a gas-phase global model of the oxygen–water-vapour bubble discharge feeds an empirical transfer of reactive "
    f"species into the water and a Hom disinfection model {R('hom')}. A comparison screen places model, OES and probe "
