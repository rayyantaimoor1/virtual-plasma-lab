s.h2("1.8 Related System Analysis/Literature Review")
s.h3("1.8.1 Literature Review")
s.p("**Global (0D) discharge models.** Lieberman and Lichtenberg show that, for a low-pressure discharge, the particle "
    "balance between ionization in the volume and ion loss at the walls fixes the electron temperature independently "
    "of the absorbed power, and the power balance then fixes the electron density "
    f"{R('lieberman')}. Lee and Lieberman extended this approach to argon and oxygen mixtures, including negative ions "
    f"{R('leelieb')}, and simulation benchmarks for capacitive discharges by Turner et al. provide reference values for "
    f"testing models {R('turner')}. These models are fast enough for interactive use, which is why they are chosen here "
    "instead of fluid or particle-in-cell codes; their weakness is the lack of spatial information, which this project "
    "addresses with a 1D axial profile for Stage 1 as requested by the supervisor.")
s.p("**Electron energy distribution and rate data.** At pressures of tens of pascals the electron energy distribution "
    f"in an RF argon discharge departs from a Maxwellian, and Godyak et al. measured such distributions directly {R('godyak')}. "
    "The Druyvesteyn form, which falls faster at high energy, is the supervisor's choice for low pressure, and the "
    f"Druyvesteyn second-derivative method {R('druyvesteyn')} is also the standard way to extract the distribution from a "
    f"probe curve. Rate coefficients are obtained by integrating LXCat cross-sections {R('lxcat')} over the chosen "
    f"distribution, the approach used by the BOLSIG+ solver {R('hagelaar')}.")
s.p("**Optical emission spectroscopy.** Zhu and Pu developed a collisional-radiative model of the argon 1s and 2p "
    f"levels valid from 1 Pa to atmospheric pressure {R('zhupu_cr')} and a line-ratio method for T~e~ and n~e~ in argon–"
    f"nitrogen plasmas {R('zhupu_oes')}. Their work shows that 2p populations in such plasmas are not in Boltzmann "
    "equilibrium, so an excitation temperature from a Boltzmann plot must not be reported as the electron temperature; "
    "the system therefore shows both and explains the difference. Bruggeman et al. reviewed gas-temperature methods and "
    "warned that N~2~ rotational temperatures in argon-rich plasmas can be distorted by energy transfer from argon "
    f"metastables {R('bruggeman_tgas')}, which is why the system uses the N~2~ (1,0) band at 315.9 nm with an NH overlap "
    "check and offers Doppler broadening only when the instrument resolution allows it. For dense underwater plasmas, "
    f"Stark broadening of H-alpha gives n~e~ through the Gigosos–González–Cardeñoso relation {R('gigosos')}.")
s.p("**Langmuir probes.** Chen's review gives the OML theory for thin cylindrical probes and its validity limits, the "
    f"effect of RF potential oscillation and practical analysis steps {R('chen')}. A COMSATS Plasma Research Laboratory "
    "study of a low-pressure Ar–O~2~ discharge used a single tungsten probe of radius 0.195 mm and 5 mm length swept from "
    f"−20 to +50 V and obtained the EEDF by the Druyvesteyn method {R('wali')}; these probe dimensions and sweep settings "
    "are used as defaults because the supervisor did not specify a probe type.")
s.p("**Underwater plasma disinfection.** Reviews by Locke et al. and Bruggeman et al. describe how discharges in and "
    "in contact with water produce O~3~, H~2~O~2~, OH and UV, and how these species transfer into the liquid "
    f"{R('locke', 'bruggeman_liquid')}. A COMSATS-linked underwater capillary discharge study reported the OH (309 nm), "
    f"H-alpha (656 nm) and atomic oxygen (777 and 844 nm) lines and DNA reduction of *E. coli* {R('ahmed')}. The Hom model "
    f"{R('hom')}, chosen by the supervisor, describes survival curves with shoulders or tails that a single-exponential "
    f"model cannot fit. Typical municipal waste-water properties are taken from Metcalf & Eddy {R('metcalf')}.")
s.p("**Machine learning on simulation data.** Tree ensembles, such as Random Forests and gradient-boosted trees like "
    f"XGBoost {R('breiman', 'chen_xgb')}, remain stronger than deep networks on tabular data of this kind {R('grinsztajn')}, "
    "which is why the AI module uses them. Conformal prediction turns any regressor into one with prediction intervals "
    f"of stated coverage {R('angelopoulos')}. Isolation Forest finds anomalies by random partitioning and needs no "
    f"labelled faults {R('liu_if')}. SHAP attributes each prediction to its inputs with Shapley values {R('lundberg')}, "
    f"and differential evolution searches a bounded design space without gradients {R('storn')}. Because the training "
    "data come from the twin, every AI output can be checked against a known physical answer, and simple baselines "
    "(ridge regression, range checks) show whether the learning adds real value.")
s.p("**Gap addressed.** The literature provides each model separately, but no reviewed source connects discharge "
    "settings, a solved plasma state, synthetic OES and probe signals, their analysis and a tolerance-based validation "
    "in one environment, applies the same chain to an underwater disinfection plasma, or couples it to AI that learns "
    "from the physics and is verified by it. This project fills that gap.")

