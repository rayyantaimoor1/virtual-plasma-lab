s.h2("2.5 Requirement Identifying Technique")
s.p("Two complementary techniques were used. The first is **mockup-based requirement analysis**. Acting as UI/UX "
    "designers for a separate implementation team, the authors broke each feature into screens, gave every screen a "
    "mockup identifier (M1 to M16), and built them as a clickable HTML prototype (Appendix A) so the supervisor could "
    "walk through the workflow. Each interactive element on each screen (input, toggle, button, chart, table or message) "
    "was then turned into a feature-level functional requirement, and the policy that governs its behaviour was recorded "
    "as a business rule. Domain values in the business rules come from the supervisor's written questionnaire answers; "
    "where the supervisor left an item blank, a published source is cited (Appendix C lists every value and its source).")
s.p("The second technique is the **event–response table**. Much of this system's behaviour happens behind the screens: "
    "solving the plasma models, checking convergence, loading reference data, parsing files, applying the citation "
    "filter and enforcing the tolerance. These backend behaviours were identified as events, and for each event the "
    "trigger, source, system state before, response, system state after and exception handling were recorded "
    "(Section 2.6.17). Functional requirements were then derived from the events (Section 2.6.18).")
s.p("Requirement identifiers follow the pattern FRm.n, where m is the mockup number (1–16) and n the requirement on that "
    "screen; m = 17 is used for requirements derived from backend events. Every requirement is written so that it can be "
    "tested, and the traceability matrix in Appendix B links business objectives, modules, use cases, mockups and "
    "requirements.")

