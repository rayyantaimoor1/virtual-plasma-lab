s.h1("2. Problem Statement", chapter="2")
s.p("Plasma diagnostics are learned by doing, but doing is expensive. A low-pressure RF plasma system needs a vacuum "
    "chamber, pumps, gas controllers, an RF generator with a matching network, a spectrometer and a probe system, and "
    "the laboratory is shared between many users. A student therefore gets only a few hours of operating time, often "
    "without being able to repeat a run or explore the full range of power, pressure and gas flow.")
s.p("Interpreting the results is also hard. The emission spectrum depends on the electron temperature, the electron "
    "density and the electron energy distribution through a chain of atomic processes, and a probe curve is distorted "
    "by the RF sheath oscillation. Students who see only the final spectrum or curve cannot tell which physical cause "
    "produced which feature, and they rarely check one diagnostic against another.")
s.p("Existing software does not close this gap. General multiphysics packages are costly and require expertise in "
    "finite-element modelling, while free tools each address one step and must be joined by hand in spreadsheets. "
    "The same problem exists for underwater plasma disinfection, where the link from pulse voltage, frequency and gas "
    "flow to reactive species and finally to bacterial log reduction is usually explored only by trial and error.")
s.p("Finally, when measured data become available, there is no consistent, tolerance-based way to compare them with "
    "theory and with the other diagnostic, so errors in either the experiment or the analysis can go unnoticed. This "
    "project addresses all of these problems with one integrated, physics-based virtual laboratory.")

