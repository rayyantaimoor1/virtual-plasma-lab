s.h1("1. Introduction", chapter="1")
s.p("Plasma diagnostics are how physicists learn what a plasma is doing. Optical emission spectroscopy reads the light "
    "emitted by excited atoms and molecules to infer temperatures and densities, and a Langmuir probe, a small "
    "electrode inserted into the plasma, measures a current–voltage curve from which the electron temperature, the "
    "electron density and the electron energy distribution are extracted. Learning to use and interpret these "
    "techniques requires many repeated experiments, which are hard to obtain on shared laboratory equipment.")
s.p("This project builds a software digital twin of the experiments defined by the supervisor, a plasma physicist "
    "whose research idea the project is. It has three stages. **Stage 1** is a low-pressure argon plasma generated in a "
    "13.56 MHz capacitively coupled (CCP) chamber and diagnosed by OES. **Stage 2** is an underwater, high-pressure "
    "oxygen plasma generated inside gas bubbles by a pulsed DC supply and used to disinfect municipal waste water; OES "
    "is applied to it as well. **Stage 3** is Langmuir probe diagnostics, applied to the Stage 1 plasma only. Stage 1 is "
    "the most important stage, but all three are mandatory.")
s.p("For each stage, the user sets the controls that exist on the real equipment, the platform solves physics-based "
    "models for the plasma state, and it then produces the signal a real instrument would record: an emission "
    "spectrum, a probe current–voltage curve or a bacterial survival curve. These signals are analysed with the same "
    "methods used in the laboratory, compared with each other and with the model, and validated against published "
    "data and, when available, against measurements from the laboratory. The platform has two core modules: "
    "**Core Module 1, the Digital Twin**, which holds all of this physics, and **Core Module 2, the AI Module**, which "
    "learns from data generated by the twin to infer plasma parameters from spectra, detect physics-relationship "
    "anomalies, explain the twin through a fast surrogate, and recommend settings that are verified by re-running the "
    "twin.")
s.p("The platform is developed in Python with Streamlit for the user interface, Plotly for interactive charts, NumPy "
    "and SciPy for the numerical models, scikit-learn, XGBoost and SHAP for the AI module, and SQLite for storing "
    "sessions. It runs on an ordinary laptop with no "
    "laboratory hardware, and it demonstrates how software engineering, numerical computing, machine learning, "
    "databases and human–computer interaction combine to model a real physical process.")

